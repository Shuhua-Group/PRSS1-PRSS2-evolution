memory.limit(15000)
library(GenomicFeatures)
txdb<-loadDb("../NA12878_anot/txdb.NA12878.gencode34.add_PRSS3P2_TRY7.mainChr.sqlite")
library(AnnotationForge)
library(AnnotationDbi)
orgdb<-loadDb("../NA12878_anot/org.Hsapiens.eg.sqlite")
library(ArchR)
library(BSgenome)
library(BSgenome.Hsapiens.NCBI.NA12878)
genomeAnnotation = createGenomeAnnotation(genome = BSgenome.Hsapiens.NCBI.NA12878)
geneAnnotation <- createGeneAnnotation(TxDb = txdb, OrgDb = orgdb, annoStyle = "GID")
inputFiles2='fragments.tsv.gz'
names(inputFiles2)='ENCDO856ZOJ-spleen'
ArrowFiles2 <- createArrowFiles(inputFiles = inputFiles2, sampleNames = names(inputFiles2), genomeAnnotation = genomeAnnotation, geneAnnotation = geneAnnotation, force = TRUE)
proj_spleen_HOM5<-ArchRProject(ArrowFiles=ArrowFiles2, outputDirectory="AGCN3liftover-atac", copyArrows=TRUE, geneAnnotation = geneAnnotation, genomeAnnotation = genomeAnnotation)
proj_spleen_HOM5 <- addIterativeLSI(ArchRProj = proj_spleen_HOM5, useMatrix = "TileMatrix", name = "IterativeLSI", iterations = 2, clusterParams = list(resolution = c(0.2), sampleCells = 10000, n.start = 10), varFeatures = 25000, dimsToUse = 1:30)
saveArchRProject(ArchRProj = proj_spleen_HOM5)
proj_spleen_HOM5<-addClusters(input=proj_spleen_HOM5, reducedDims = "IterativeLSI", method="Seurat", name="Clusters", resolution=0.8)
proj_spleen_HOM5 <- addUMAP(ArchRProj = proj_spleen_HOM5, reducedDims = "IterativeLSI", name = "UMAP", nNeighbors = 30, minDist = 0.5, metric = "cosine")
pUMAP <- plotEmbedding(ArchRProj = proj_spleen_HOM5, colorBy = "cellColData", name = "Clusters", embedding = "UMAP")
plotPDF(pUMAP, name = "Plot-UMAP-Clusters.pdf", ArchRProj = proj_spleen_HOM5, addDOC = FALSE, width = 5, height = 5)
proj_spleen_HOM5 <- addGroupCoverages(ArchRProj = proj_spleen_HOM5, groupBy = "Clusters")
saveArchRProject(ArchRProj = proj_spleen_HOM5)
proj_spleen_HOM5 <- addReproduciblePeakSet(ArchRProj = proj_spleen_HOM5, groupBy = "Clusters", peakMethod = "Tiles", method = "p")
proj_spleen_HOM5 <- addPeakMatrix(proj_spleen_HOM5)
saveArchRProject(ArchRProj = proj_spleen_HOM5)
proj_spleen_HOM5 <- addCoAccessibility(ArchRProj = proj_spleen_HOM5, reducedDims = "IterativeLSI")
markerGenes<-c("PRSS1")
cA <- getCoAccessibility(ArchRProj = proj_spleen_HOM5, corCutOff = 0.5, resolution = 10000, returnLoops = TRUE)
p <- plotBrowserTrack(ArchRProj = proj_spleen_HOM5, groupBy = "Clusters", geneSymbol = markerGenes, upstream = 5000, downstream = 50000, loops = cA )
plotPDF(plotList = p, name = "Plot-Tracks-Marker-Genes-with-CoAccessibility-cor0.5-r10k.pdf", ArchRProj = proj_spleen_HOM5, addDOC = FALSE, width = 5, height = 5)
